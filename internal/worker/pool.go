// Пакет worker реализует универсальный пул воркеров с ограниченным
// параллелизмом. Пакет ничего не знает о сайтах: тип задачи и тип результата
// задаёт вызывающий код через параметры типа (generics).
package worker

import (
	"context"
	"sync"
)

// Run обрабатывает задачи jobs фиксированным числом горутин (workers) и
// возвращает результаты — в произвольном порядке.
//
// J и R — параметры типа (generics, Go 1.18+): J — тип задачи, R — тип
// результата; any означает «любой тип». Для сервиса проверок J = site.Site,
// R = site.Check, и компилятор выводит их сам.
//
// Когда ctx отменён, ещё не розданные задачи пропускаются. Функция fn тоже
// получает ctx и должна сама прекращать работу при его отмене.
//
// Схема работы:
//
//	производитель ──jobCh──> воркер 1..N ──resCh──> сборщик (эта функция)
func Run[J, R any](ctx context.Context, workers int, jobs []J, fn func(context.Context, J) R) []R {
	// Не меньше одного воркера и не больше числа задач: нет смысла
	// запускать 5 горутин ради 2 задач. Для пустого jobs получится 0.
	if workers < 1 {
		workers = 1
	}
	workers = min(workers, len(jobs))

	// НЕбуферизированный канал задач: отправка блокируется, пока свободный
	// воркер не заберёт задачу. Поэтому «в работе» никогда не больше workers задач.
	jobCh := make(chan J)
	// Буферизированный канал результатов: воркер кладёт результат и сразу
	// берёт следующую задачу, не дожидаясь, пока сборщик прочитает предыдущий.
	resCh := make(chan R, workers)

	var wg sync.WaitGroup
	for range workers { // цикл по числу (Go 1.22+): повторить workers раз
		wg.Add(1)
		go func() {
			defer wg.Done()
			// range по каналу читает значения, пока канал не закроют.
			for job := range jobCh {
				resCh <- fn(ctx, job)
			}
		}()
	}

	// Производитель: раздаёт задачи воркерам.
	go func() {
		// Закрытие jobCh — сигнал воркерам «задач больше не будет».
		// Правило Go: канал закрывает тот, кто в него ОТПРАВЛЯЕТ.
		defer close(jobCh)
		for _, job := range jobs {
			// select ждёт, что произойдёт раньше: воркер возьмёт задачу
			// или контекст отменят. Без него при отмене производитель
			// мог бы навсегда зависнуть на отправке.
			select {
			case jobCh <- job:
			case <-ctx.Done():
				return
			}
		}
	}()

	// Закрываем канал результатов, когда ВСЕ воркеры закончили, — тогда цикл
	// сбора ниже завершится. Это делается в отдельной горутине: если бы текущая
	// горутина сначала вызвала wg.Wait(), а потом начала читать resCh, воркеры
	// заблокировались бы на отправке в заполненный буфер — взаимная блокировка.
	go func() {
		wg.Wait()
		close(resCh)
	}()

	// Сборщик: память сразу выделена под максимум результатов,
	// поэтому append не будет перевыделять массив.
	results := make([]R, 0, len(jobs))
	for r := range resCh {
		results = append(results, r)
	}
	return results
}
